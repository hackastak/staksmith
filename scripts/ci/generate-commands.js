#!/usr/bin/env node
/**
 * Generate a slash command for every skill so each skill is invocable on demand
 * across harnesses (Claude Code + OpenCode).
 *
 * Why this exists
 * ---------------
 * In Claude Code, skills auto-activate; in OpenCode a skill is only loaded as
 * passive context via the `instructions` array and cannot be invoked on demand.
 * A slash command is the portable way to invoke a skill by name in either tool.
 * These commands SHIP with the plugin (they live in `commands/` and
 * `.opencode/commands/`, both listed in package.json "files"), so they are
 * generated + committed here at authoring time, NOT at each user's install time.
 *
 * What it does
 * ------------
 * For each `skills/<name>/SKILL.md`, ensures a same-named command exists in the
 * selected surface(s):
 *   - Claude Code:  `commands/<name>.md`
 *   - OpenCode:     `.opencode/commands/<name>.md` + a `command.<name>` entry in
 *                   `.opencode/opencode.json`
 *
 * Existing (hand-authored) command files are never overwritten. Generated files
 * carry a marker comment so they are easy to distinguish and safe to regenerate.
 *
 * Usage
 * -----
 *   node scripts/ci/generate-commands.js                 # generate missing (both surfaces)
 *   node scripts/ci/generate-commands.js --surface=claude
 *   node scripts/ci/generate-commands.js --surface=opencode
 *   node scripts/ci/generate-commands.js --check         # CI: fail if any missing, write nothing
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '../..');
const SKILLS_DIR = path.join(ROOT, 'skills');
const CLAUDE_COMMANDS_DIR = path.join(ROOT, 'commands');
const OPENCODE_COMMANDS_DIR = path.join(ROOT, '.opencode/commands');
const OPENCODE_CONFIG = path.join(ROOT, '.opencode/opencode.json');

const GENERATED_MARKER =
  '<!-- GENERATED by scripts/ci/generate-commands.js from the same-named skill. ' +
  'Safe to edit: the generator only creates missing commands and never overwrites. -->';

function parseArgs(argv) {
  const args = { check: false, surface: 'both' };
  for (const arg of argv.slice(2)) {
    if (arg === '--check') args.check = true;
    else if (arg.startsWith('--surface=')) args.surface = arg.slice('--surface='.length);
    else {
      console.error(`Unknown argument: ${arg}`);
      process.exit(2);
    }
  }
  if (!['both', 'claude', 'opencode'].includes(args.surface)) {
    console.error(`--surface must be one of: both, claude, opencode`);
    process.exit(2);
  }
  return args;
}

/**
 * Extract `name` and `description` from a SKILL.md YAML frontmatter block.
 * Handles plain scalars, single/double-quoted scalars, and block scalars
 * (`|`, `>`, with optional chomping/indent indicators).
 */
function parseFrontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return {};
  const lines = match[1].split('\n');
  const result = {};
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const kv = line.match(/^([A-Za-z0-9_-]+):\s?(.*)$/);
    if (!kv) continue;
    const key = kv[1];
    let value = kv[2];

    // Block scalar: value is on following, more-indented lines.
    if (/^[|>][+-]?\d*\s*$/.test(value.trim())) {
      const collected = [];
      let j = i + 1;
      const baseIndent = (lines[j] && lines[j].match(/^(\s*)/)[1].length) || 0;
      while (j < lines.length && (lines[j].trim() === '' || lines[j].search(/\S/) >= baseIndent)) {
        collected.push(lines[j].slice(baseIndent));
        j++;
      }
      i = j - 1;
      value = collected.join(' ').replace(/\s+/g, ' ').trim();
    } else {
      value = value.trim();
      if (
        (value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))
      ) {
        value = value.slice(1, -1);
      }
    }
    result[key] = value;
  }
  return result;
}

/** Emit a description safely as a double-quoted YAML string on one line. */
function yamlQuote(text) {
  const clean = String(text).replace(/\s+/g, ' ').trim().replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  return `"${clean}"`;
}

function listSkills() {
  if (!fs.existsSync(SKILLS_DIR)) return [];
  return fs
    .readdirSync(SKILLS_DIR, { withFileTypes: true })
    .filter(entry => entry.isDirectory() && fs.existsSync(path.join(SKILLS_DIR, entry.name, 'SKILL.md')))
    .map(entry => {
      const skillMd = fs.readFileSync(path.join(SKILLS_DIR, entry.name, 'SKILL.md'), 'utf8');
      const fm = parseFrontmatter(skillMd);
      return {
        name: fm.name || entry.name,
        dir: entry.name,
        description: fm.description || `Invoke the ${entry.name} skill.`
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

function claudeCommandBody(skill) {
  return `---
description: ${yamlQuote(skill.description)}
---

${GENERATED_MARKER}

# /${skill.name}

Invoke the **\`${skill.name}\`** skill and apply it to the request below. The full workflow, triggers, and output format live in \`skills/${skill.dir}/SKILL.md\` — read it and follow it.

## Usage

\`\`\`text
/${skill.name} [request or arguments]
\`\`\`

$ARGUMENTS
`;
}

function opencodeCommandBody(skill) {
  return `---
description: ${yamlQuote(skill.description)}
---

${GENERATED_MARKER}

Load the skill defined in \`skills/${skill.dir}/SKILL.md\`, then follow its workflow to handle the request below. Treat that file as the authoritative instructions for this command.

$ARGUMENTS
`;
}

function ensureClaudeCommand(skill, { check, missing, created }) {
  const file = path.join(CLAUDE_COMMANDS_DIR, `${skill.name}.md`);
  if (fs.existsSync(file)) return;
  if (check) {
    missing.push(`commands/${skill.name}.md`);
    return;
  }
  fs.writeFileSync(file, claudeCommandBody(skill));
  created.push(`commands/${skill.name}.md`);
}

function ensureOpencodeCommand(skill, config, { check, missing, created }) {
  const file = path.join(OPENCODE_COMMANDS_DIR, `${skill.name}.md`);
  const hasFile = fs.existsSync(file);
  const hasEntry = Boolean(config.command && config.command[skill.name]);
  if (hasFile && hasEntry) return false;

  if (check) {
    if (!hasFile) missing.push(`.opencode/commands/${skill.name}.md`);
    if (!hasEntry) missing.push(`.opencode/opencode.json → command.${skill.name}`);
    return false;
  }

  if (!hasFile) {
    fs.writeFileSync(file, opencodeCommandBody(skill));
    created.push(`.opencode/commands/${skill.name}.md`);
  }
  let mutated = false;
  if (!hasEntry) {
    config.command = config.command || {};
    config.command[skill.name] = {
      description: String(skill.description).replace(/\s+/g, ' ').trim(),
      template: `{file:commands/${skill.name}.md}\n\n$ARGUMENTS`
    };
    created.push(`.opencode/opencode.json → command.${skill.name}`);
    mutated = true;
  }
  return mutated;
}

function main() {
  const args = parseArgs(process.argv);
  const skills = listSkills();
  const doClaude = args.surface === 'both' || args.surface === 'claude';
  const doOpencode = args.surface === 'both' || args.surface === 'opencode';

  const missing = [];
  const created = [];

  if (doClaude && !fs.existsSync(CLAUDE_COMMANDS_DIR)) fs.mkdirSync(CLAUDE_COMMANDS_DIR, { recursive: true });
  if (doOpencode && !fs.existsSync(OPENCODE_COMMANDS_DIR)) fs.mkdirSync(OPENCODE_COMMANDS_DIR, { recursive: true });

  let config = {};
  let configMutated = false;
  if (doOpencode) {
    config = JSON.parse(fs.readFileSync(OPENCODE_CONFIG, 'utf8'));
  }

  for (const skill of skills) {
    if (doClaude) ensureClaudeCommand(skill, { check: args.check, missing, created });
    if (doOpencode) {
      const mutated = ensureOpencodeCommand(skill, config, { check: args.check, missing, created });
      configMutated = configMutated || mutated;
    }
  }

  if (doOpencode && configMutated && !args.check) {
    fs.writeFileSync(OPENCODE_CONFIG, `${JSON.stringify(config, null, 2)}\n`);
  }

  if (args.check) {
    if (missing.length > 0) {
      console.error(`Missing ${missing.length} skill→command artifact(s):`);
      for (const item of missing) console.error(`  - ${item}`);
      console.error('\nRun: node scripts/ci/generate-commands.js');
      process.exit(1);
    }
    console.log(`All ${skills.length} skills have matching commands (surface: ${args.surface}).`);
    return;
  }

  if (created.length === 0) {
    console.log(`Nothing to generate — all ${skills.length} skills already have commands (surface: ${args.surface}).`);
    return;
  }
  console.log(`Generated ${created.length} artifact(s) for ${skills.length} skills (surface: ${args.surface}):`);
  for (const item of created) console.log(`  + ${item}`);
}

main();
